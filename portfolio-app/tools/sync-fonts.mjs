/**
 * Copies the WOFF2 subsets the site needs out of the installed @fontsource
 * packages into the source tree and writes `src/styles/_fonts.scss` to match.
 *
 * Three languages ship (English, Ukrainian, Polish), so every face needs
 * latin, latin-ext (Polish diacritics) and cyrillic (Ukrainian). Each subset
 * keeps fontsource's own `unicode-range`, so a browser only downloads the
 * files for the scripts actually on screen.
 *
 * Run after bumping a font package: `npm run fonts:sync`.
 */
import { copyFileSync, mkdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const target = join(root, 'src/styles/fonts');
const scss = join(root, 'src/styles/_fonts.scss');

const SUBSETS = ['latin', 'latin-ext', 'cyrillic'];
const FACES = [
  { pkg: 'unbounded', weights: [600, 800] },
  { pkg: 'onest', weights: [400, 500, 600] },
  { pkg: 'jetbrains-mono', weights: [400, 500] },
];

rmSync(target, { recursive: true, force: true });
mkdirSync(target, { recursive: true });

const blocks = [];
for (const { pkg, weights } of FACES) {
  for (const weight of weights) {
    const css = readFileSync(join(root, 'node_modules/@fontsource', pkg, `${weight}.css`), 'utf8');
    for (const block of css.split('/* ').slice(1)) {
      const subset = SUBSETS.find((s) => block.startsWith(`${pkg}-${s}-${weight}-normal */`));
      if (!subset) continue;
      const family = block.match(/font-family: '([^']+)'/)[1];
      const range = block.match(/unicode-range: ([^;]+);/)[1];
      const file = `${pkg}-${subset}-${weight}-normal.woff2`;
      copyFileSync(join(root, 'node_modules/@fontsource', pkg, 'files', file), join(target, file));
      blocks.push(
        `@font-face {\n  font-family: '${family}';\n  font-style: normal;\n  font-weight: ${weight};\n` +
          `  font-display: swap;\n  src: url('./fonts/${file}') format('woff2');\n  unicode-range: ${range};\n}\n`,
      );
      console.log(`copied ${file}`);
    }
  }
}

writeFileSync(
  scss,
  '// GENERATED by tools/sync-fonts.mjs from the @fontsource packages. Do not edit by hand.\n' +
    '// Self-hosted WOFF2 subsets: latin, latin-ext and cyrillic. No CDN, no runtime request.\n\n' +
    blocks.join('\n'),
);
console.log(`wrote ${blocks.length} @font-face rules`);
